"""Deterministic scene → SVG/TXT/HTML. No network or rendering dependency.

Run --check to compare generated bytes without writing. Numerical fixture
validation is separate from geometry, so a plausible drawing cannot silently
replace its mathematical contract. PDF conversion lives in publication/build.py.
"""
from pathlib import Path
