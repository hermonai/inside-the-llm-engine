def validate_fixture(s):
    f,k=s['fixture'],s['kind']
    if k=='tensor':
        assert sum(i*j for i,j in zip(f['index'],f['strides']))==f['element_offset']
        assert f['byte_offset']==4*f['element_offset']
    elif k=='gemv':
        assert [math.fsum(a*b for a,b in zip(row,f['input'])) for row in f['weight']]==f['output']
    elif k=='heads': assert len(f['flat'])==f['heads']*f['head_dimension']
    elif k=='rope':
        for p in f['positions']:
            a=p*f['omega']; assert math.isclose(math.cos(a)**2+math.sin(a)**2,1,abs_tol=1e-14)
    elif k=='attention':
        scores=[math.fsum(a*b for a,b in zip(f['query'],row))/math.sqrt(2) for row in f['keys'][:f['position']+1]]
        weights=[math.exp(x-max(scores)) for x in scores]; total=math.fsum(weights)
        prob=[x/total for x in weights]+[0]
        assert all(math.isclose(a,b,abs_tol=1e-12) for a,b in zip(prob,f['probabilities']))
        output=[math.fsum(p*row[j] for p,row in zip(prob,f['values'])) for j in range(2)]
        assert all(math.isclose(a,b,abs_tol=1e-12) for a,b in zip(output,f['output']))
    elif k=='cache': assert [2*f['layers']*t*f['kv_heads']*f['head_dimension']*f['bytes_per_element'] for t in f['lengths']]==[16,32,48,64]
    elif k=='batch': assert [row[-1] for row in f['rows']]==['·','D','D']


def animation(s):
    sections=[]
    for n in s['frames']:
        svg=render(s,n).replace('id="title"',f'id="title{n}"').replace('id="desc"',f'id="desc{n}"').replace('title desc',f'title{n} desc{n}')
        sections.append('<section class="frame" '+('hidden' if n else '')+'>'+svg+'</section>')
    frames=''.join(sections)
    return '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>'+html.escape(s['title'])+'</title><style>body{font:18px system-ui;margin:1rem auto;max-width:1000px;color:#152b3c}svg{width:100%;height:auto}button,input{font:inherit;min-height:44px}button:focus-visible,input:focus-visible{outline:3px solid #163d70}p{line-height:1.5}</style><main><h1>'+html.escape(s['title'])+'</h1><button id="play" type="button">Play</button> <button id="prev" type="button">Previous</button> <button id="next" type="button">Next</button> <label>Frame <input id="step" type="range" min="0" max="3" value="0"></label><output id="state" aria-live="polite">Frame 1 of 4</output>'+frames+'<p>'+html.escape(s['caption'])+'</p><p><a href="'+s['kind']+'.svg">Complete static explanation</a> · '+html.escape(s['status'])+'</p></main><script src="player.js"></script></html>\n'


def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    manifest=json.loads((ROOT/'figures/manifest.json').read_text()); seen=set(); outputs={}
    for entry in manifest['figures']:
        assert entry['id'] not in seen, 'duplicate ID'; seen.add(entry['id'])
        for field in ['id','chapter','title','purpose','concepts','source','generated','caption','alt','evidence']: assert entry[field], field
        s=json.loads((ROOT/entry['source']).read_text()); assert s['id']==entry['id']
        assert s['caption']==entry['caption'] and s['alt']==entry['alt']
        assert (ROOT/entry['evidence']).is_file()
        if s['legacy']: assert (ROOT/s['legacy']).is_file()
        validate_fixture(s)
        svg=render(s); ET.fromstring(svg)
        base='figures/generated/'+s['kind']
        outputs[base+'.svg']=svg
        maps={
            'tensor':['logical A[1,2] ──▶ offset 3×1+2 = 5 ──▶ byte offset 20', 'owner [1 2 3 4 5 6] ◁── immutable TensorView'],
            'gemv':['W row [1 2 3] × x [2 −1 0.5]', '          ║ matched-index products', '          ▼', '       [2 −2 1.5] ──▶ sum in order ──▶ y₀ = 1.5'],
            'pipeline':['token 1 ──▶ E[1,:] ══▶ x [4] ══▶ RMSNorm ══▶ x̂ [4]', '                                                 ├┄┄▶ Wq ══▶ Q [2,2]', '                                                 ├┄┄▶ Wk ══▶ K [2,2]', '                                                 └┄┄▶ Wv ══▶ V [2,2]'],
            'heads':['flat [−1.5 3.5 −1 3] ──▷ same storage, new metadata', 'head 0 [−1.5 3.5]       head 1 [−1 3]'],
            'rope':['p=0 (1,0) ──▶ p=1 (.866,.5) ──▶ p=2 (.5,.866) ──▶ p=3 (0,1)', 'Each state applies R(pω) to the original pair; arrows order positions.'],
            'attention':['Q,K ══▶ dot / √2 ──▶ causal mask ──▶ softmax ──▶ weighted V', '        [0,1,9]      [0,1,−∞]       [.269,.731,0]   [.538,2.924]'],
            'cache':['T=1  K0             V0', 'T=2  K0 K1          V0 V1', 'T=3  K0 K1 K2       V0 V1 V2', 'T=4  K0 K1 K2 K3    V0 V1 V2 V3'],
            'batch':['iteration   0   1   2   3', 'Request A   P   D   D   ·', 'Request B   ·   P   D   D', 'Request C   ·   ·   P   D'],
            'sequence':['API ──▶ submit queue ──▶ worker ──▶ Context::decode_batch', 'API ◀┄┄ sample/stream ◀┄┄ worker ◀┄┄ logits/status', 'Legend: solid call; dashed return; worker owns Context and Batch.'],
            'architecture':['Client ┄┄▶ API ┄┄▶ Dispatcher ┄┄▶ Batched worker [CURRENT]', '                                   │', '                                   ▼', 'parameters ══▶ llama.cpp graph ◀── context / KV state', '                     │', '                     ▼', '             backend ──▶ configured CPU / GPU', 'PREVIEW: paged runtime; LIBRARY: native components; separate integration gates.']}
        lines=[s['id'],s['title'],s['status'],'',*maps[s['kind']],'']
        for label in [s['purpose'],*s['contract'],'Fixture: '+json.dumps(s['fixture'],ensure_ascii=False)]:
            lines.extend(textwrap.wrap(label,94)); lines.append('')
        lines+=['Source: '+entry['source'],'Implementation/evidence: '+s['code']]
        outputs[base+'.txt']='\n'.join(lines)+'\n'
        if s['animate']: outputs[base+'.html']=animation(s)
        assert set(entry['generated'])=={base+'.svg',base+'.txt'}
        assert entry['animation']==(base+'.html' if s['animate'] else None)
    outputs['figures/generated/player.js']=(ROOT/'figures/player.js').read_text()
    for path,data in outputs.items():
        dest=ROOT/path
        if args.check:
            assert dest.is_file() and dest.read_text()==data, 'missing or stale: '+path
        else:
            dest.parent.mkdir(parents=True,exist_ok=True); dest.write_text(data)
    print(f'figure {"check" if args.check else "build"} passed: {len(seen)} scenes, {len(outputs)} deterministic artifacts')


if __name__=='__main__': main()
