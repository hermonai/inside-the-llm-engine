INK, MUTED, BLUE, TEAL, GOLD = '#152b3c', '#465c6b', '#dcecf7', '#dcefe7', '#f4ead2'


class Drawing:
    def __init__(self, scene):
        self.items = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 720" role="img" aria-labelledby="title desc"><title id="title">{html.escape(scene["title"])}</title><desc id="desc">{html.escape(scene["alt"])}</desc>', '<rect width="1000" height="720" fill="white"/>']
        self.text(40, 38, scene['id'] + '  /  ' + scene['status'], 14, MUTED)
        self.text(40, 84, scene['title'], 30)
        self.line(40, 109, 960, 109)
        for i, line in enumerate(textwrap.wrap(scene['purpose'], 88)):
            self.text(40, 140 + 23*i, line, 19)

    def text(self, x, y, label, size=19, color=INK, anchor='start'):
        self.items.append(f'<text x="{x}" y="{y}" fill="{color}" font-family="DejaVu Sans, sans-serif" font-size="{size}" text-anchor="{anchor}">{html.escape(str(label))}</text>')

    def line(self, x, y, xx, yy, dashed=False, color=INK, width=1.5):
        dash = ' stroke-dasharray="6 5"' if dashed else ''
        self.items.append(f'<line x1="{x}" y1="{y}" x2="{xx}" y2="{yy}" stroke="{color}" stroke-width="{width}"{dash}/>')

    def arrow(self, x, y, xx, yy, dashed=False):
        self.line(x, y, xx, yy, dashed, width=2.5)
        a = math.atan2(yy-y, xx-x)
        pts = [(xx, yy), (xx-10*math.cos(a-.45), yy-10*math.sin(a-.45)), (xx-10*math.cos(a+.45), yy-10*math.sin(a+.45))]
        self.items.append('<polygon fill="'+INK+'" points="'+' '.join(f'{a:.2f},{b:.2f}' for a,b in pts)+'"/>')

    def box(self, x, y, w, h, label='', fill=BLUE, size=19):
        self.items.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}" stroke="{INK}" stroke-width="1.4"/>')
        for i, line in enumerate(label.split('\n')):
            self.text(x+14, y+29+i*25, line, size)

    def cells(self, x, y, values, width=72, fill=TEAL):
        for i, value in enumerate(values):
            self.box(x+i*width, y, width, 48, str(value), fill)

    def footer(self, scene):
        self.line(40, 608, 960, 608)
        yy = 638
        for contract in scene['contract']:
            for line in textwrap.wrap(contract, 99):
                self.text(40, yy, line, 15)
                yy += 21
        self.items.append('</svg>')
        return '\n'.join(self.items)+'\n'


